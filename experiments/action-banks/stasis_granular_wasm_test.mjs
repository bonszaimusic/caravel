// Real C/WASM opt-in STASIS granular engine: FM-1 encoders, dual capture,
 // real audio, safe HOLD, decimated sample rates and unchanged FX controls.
import fs from 'node:fs';
import assert from 'node:assert/strict';
const {instance}=await WebAssembly.instantiate(fs.readFileSync('build/home-perf/felucca.wasm'),{});
const e=instance.exports;
e._initialize();e.web_nor_erase();e.web_boot();
const render=ms=>{for(let n=Math.ceil(ms*44.1);n>0;){const x=Math.min(128,n);e.web_render(x);n-=x;}};
const tap=b=>{e.web_buttons(1<<b);render(70);e.web_buttons(0);render(100);};
const key=(k,ms=90)=>{e.web_keys(1<<k);render(ms);e.web_keys(0);render(120);};
const hold=k=>key(k,680);
const setting=k=>e.web_action_setup_value(k);
const dsp=k=>e.web_stasis_granular_get(k);
function turn(index,steps){e.web_enc(index,steps);render(135);}
function stereoPeak(){
 const l=new Float32Array(e.memory.buffer,e.web_out_l(),128);
 const r=new Float32Array(e.memory.buffer,e.web_out_r(),128);
 let peak=0;
 for(let j=0;j<128;j++)peak=Math.max(peak,Math.abs(l[j]),Math.abs(r[j]));
 return peak;
}
render(1300);
/* The granular DSP activates only when REVERB TYPE is STASIS. */
e.web_stasis_test_type(3);render(120);
assert.equal(dsp(0),1,'Default 186ms grain');
assert.equal(dsp(2),0,'Default HQ');
assert.equal(dsp(1),0,'Default zero scan');
assert.equal(dsp(3),0,'Default forward');
tap(6);tap(6);
assert.equal(e.web_action_state()&1,1,'HOME double tap');
key(22);assert.equal((e.web_action_state()>>8)&255,1,'STASIS bank');
hold(22);assert.equal((e.web_action_state()>>1)&1,1,'SETUP ON');
assert.equal(setting(0),90,'old STR remains on FX page');
assert.equal(dsp(14),0,'STASIS FX page is default');
turn(0,1);assert.equal(dsp(14),1,'SELECT switches to GRANULAR page');
assert.equal(setting(0),1,'K1 grain length');
turn(3,1);assert.equal(dsp(0),2,'K1 = 372ms grains');
turn(4,32);assert.equal(dsp(1),32,'K2 = independent SCAN');
turn(5,1);assert.equal(dsp(2),1,'K3 = LONG 22.05kHz recording');
turn(6,1);assert.equal(dsp(3),1,'K4 = reverse grains');
render(80);
assert.equal(dsp(8),1,'audio thread adopted LONG decimation');
assert.equal(dsp(9),2,'audio thread adopted 372ms grain');
assert.ok(dsp(12)>0&&dsp(12)<32768,'capture history window fits ring');
let screen=new Uint16Array(e.memory.buffer,e.web_screen(),240*240).slice();
let lit=0;for(let y=24+171;y<24+200;y++)for(let x=0;x<240;x++)lit+=screen[y*240+x]!==0;
assert.ok(lit>80,'real 240x240 STASIS setup LCD rendered');
e.web_test_drone(0);
assert.equal(e.web_pair_control(0,8,127),1,'track FX reverb send enabled');
e.web_keys(1<<7);
render(1500);
assert.equal(dsp(8),1,'LONG mode active');
let write=dsp(5);render(500);let delta=dsp(5)-write;
assert.ok(delta>=10900&&delta<=11150,'22.05kHz capture rate: '+delta);
assert.equal(dsp(10),1,'grain playback has captured history');
let peak=stereoPeak();render(400);peak=Math.max(peak,stereoPeak());
assert.ok(peak>0.00001,'audible DSP peak: '+peak);
assert.ok(Number.isFinite(peak)&&peak<=2.0,'finite peak: '+peak);
assert.ok(e.web_stasis_scan_mod(1,20)>0,'SCAN MOD matrix destination');
render(200);assert.ok(dsp(13)>=0&&dsp(13)<=127,'bounded modulated SCAN');
e.web_stasis_test_hold(1);render(200);
assert.equal(dsp(11),1,'HOLD freezes retroactive audio');
const frozenWrite=dsp(5);
turn(5,1);assert.equal(dsp(2),1,'quality cannot change during HOLD');
render(400);assert.equal(dsp(5),frozenWrite,'held capture cannot be overwritten');
key(24);render(1600);assert.ok(dsp(6)>0,'ADD records into second bank');
e.web_stasis_test_hold(0);render(2700);
assert.equal(dsp(11),0,'return to LIVE');
turn(5,1);assert.equal(dsp(2),2,'DRONE 11.025kHz selected');
render(100);assert.equal(dsp(8),2,'audio thread adopted DRONE');
write=dsp(5);render(500);delta=dsp(5)-write;
assert.ok(delta>=5450&&delta<=5600,'11.025kHz capture rate: '+delta);
turn(3,-2);assert.equal(dsp(0),0,'93ms grain selected');
render(250);assert.equal(dsp(9),0,'audio thread adopted 93ms grain');
turn(6,-1);assert.equal(dsp(3),0,'reverse OFF');
turn(0,1);assert.equal(dsp(14),0,'SELECT back to FX page');
assert.equal(setting(0),90,'original STR stays canonical');
assert.equal(setting(2),32,'LAYER AMT preserved');
key(23);assert.equal(e.web_action_stasis_capt(),1,'physical STASIS HOLD action');
key(23);assert.equal(e.web_action_stasis_capt(),0,'physical STASIS RELEASE action');
e.web_keys(0);
console.log('STASIS EXPAND C/WASM PASS: 93/186/372ms grains, 22.05/11.025kHz windows, dual-bank ADD, MOD SCAN, REVERSE, HOLD safety, FX compatibility and real audio.');
