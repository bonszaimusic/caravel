def topic_page(topic, data, look, ship, version, root=ROOT):
    title, lead, sixty, sections = parse_page((root / TUT / topic["md"]).read_text(encoding="utf-8"), data)
    steps = "".join(f'<a href="#step-{n}"><span class="n">{n}</span>{e(h)}</a>' for n, h, _, _ in sections if n)
    body = [f'<p class="crumbs"><a href="../">TUTORIALS</a> / {e(topic["num"])}</p>', topic_strip(data, topic["id"]),
            f'<div class="eyebrow">TUTORIAL {e(topic["num"])} · CARAVEL {e(version)}</div><h1>{e(title)}</h1>',
            f'<div class="lead">{lead}</div>',
            (f'<div class="meta"><span class="chip">ABOUT {topic["minutes"]} MINUTES</span>'
             + ('<span class="chip">0.13.0 PREVIEW · FIRMWARE CAPTURES PENDING</span>'
                if topic.get("preview") else '<span class="chip">REAL FIRMWARE SCREENS</span>') + '</div>'), sixty]
    if steps:
        body.append(f'<nav class="steps" aria-label="Steps">{steps}</nav>')
    for n, heading, text, figs in sections:
        ident = f' id="step-{n}"' if n else ""
        head = f'<span class="num">{n}</span>' if n else ""
        devs = [f for k, f in figs if k == "device"]
        screens = [f for k, f in figs if k == "screen"]
        side = "".join(devs) + (f'<div class="row">{"".join(screens)}</div>' if screens else "")
        body.append(f'<section class="step{"" if side else " plain"}"{ident}><h2>{head}{inline(heading, Resolver(data, 1))}</h2><div class="text">{text}</div>'
                    + (f'<div class="figs">{side}</div>' if side else "") + "</section>")
    ids = [t["id"] for t in data["topics"]]
    i = ids.index(topic["id"])
    prev_t, next_t = (data["topics"][i - 1] if i else None), (data["topics"][i + 1] if i + 1 < len(ids) else None)

    def card(t, cls, label):
        if t is None:
            return "<div></div>"
        if t["status"] == "ready":
            return f'<a class="{cls}" href="../{t["id"]}/"><small>{label}</small><b>{e(t["num"])} · {e(t["title"])}</b></a>'
        return f'<div class="{cls} off"><small>{label} · in preparation</small><b>{e(t["num"])} · {e(t["title"])}</b></div>'
