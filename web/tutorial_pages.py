def check_site(site, root=ROOT):
    """The overview, every ready topic and the images they use are in the site (the links are checked by stasis_pages.check_site)."""
    site = Path(site)
    data = load_topics(root)
    need = ["tutorials/index.html", "tutorials/stasis/index.html"] + [f"tutorials/{t['id']}/index.html" for t in data["topics"] if t["status"] == "ready"]
    need += ["tutorials/img/" + n for n in used_images(data, root)] + ["tutorials/audio/" + n for n in used_audio(data, root)]
    missing = [n for n in need if not (site / n).is_file()]
    if missing:
        raise ValueError("Missing tutorial files: " + ", ".join(missing))
    print("Tutorials PASS:", sum(t["status"] == "ready" for t in data["topics"]), "ready topics, overview, STASIS lessons and images")


def check_source(root=ROOT):
    data = load_topics(root)
    problems = []
    for t in data["topics"]:
        if t["status"] != "ready":
            continue
        text = (root / TUT / t["md"]).read_text(encoding="utf-8")
        for name in re.findall(r"\]\(img/([^)\s]+)\)", text):
            if not (root / TUT / "img" / name).is_file():
                problems.append(f"{t['md']}: missing image {name}")
        for url in re.findall(r"\]\(([^)\s]+)\)", text):
            if urlsplit(url).scheme or url.startswith(("#", "img/")):
                continue
            target = (root / TUT / url.split("#")[0]).resolve()
            if url.split("#")[0] != "README.md" and not target.is_file():      # README.md is the generated overview (--write-readme)
                problems.append(f"{t['md']}: broken link {url}")
        for url in re.findall(r"\[Listen: [^\]]+\]\(([^)\s]+\.mp3)\)", text):
            if not (root / TUT / url).resolve().is_file():
                problems.append(f"{t['md']}: missing audio {url}")
        title, lead, sixty, sections = parse_page(text, data)
        if not title or not sixty or not sections:
            problems.append(f"{t['md']}: needs a title, an 'In 60 seconds' box and steps")
    if problems:
        raise ValueError("; ".join(problems))
    return data


