def e(s):
    return html.escape(str(s), quote=True)


# ------------------------------------------------------------------------------------------------ the registry
def load_topics(root=ROOT):
    data = json.loads((root / TUT / "topics.json").read_text(encoding="utf-8"))
    groups = {g["id"] for g in data["groups"]}
    ids, nums = set(), set()
    for t in data["topics"]:
        if t["id"] in ids or t["num"] in nums:
            raise ValueError("Duplicate tutorial id/number: " + t["id"])
        ids.add(t["id"]); nums.add(t["num"])
        if t["group"] not in groups or t["status"] not in ("ready", "planned"):
            raise ValueError("Bad tutorial topic: " + t["id"])
        kind = t.get("thumb_kind", "firmware")
        if kind not in ("firmware", "illustration"):
            raise ValueError("Unknown tutorial image kind: " + t["id"])
        if kind == "illustration" and not t["thumb"].endswith(".svg"):
            raise ValueError("Concept illustration must be a marked SVG: " + t["id"])
        if t.get("preview") and t["status"] != "ready":
            raise ValueError("Preview chapters must link to real source pages: " + t["id"])
        if not (root / TUT / "img" / t["thumb"]).is_file():
            raise ValueError("Missing tutorial card image: " + t["thumb"])
        if t["status"] == "ready" and not (root / TUT / t["md"]).is_file():
            raise ValueError("Missing tutorial page: " + t["md"])
    return data


def topic_of_md(data, name):
    for t in data["topics"]:
        if t["md"] == name:
            return t
    return None


# ------------------------------------------------------------------------------------------------ inline Markdown
class Resolver:
    """Where a link of a tutorial page points on the site. `depth` is how far below tutorials/ the page sits (0: the overview)."""

    def __init__(self, data, depth):
        self.data, self.depth, self.up = data, depth, "../" * depth

    def link(self, url):
        if url.startswith("@github:"):
            return GITHUB + url[8:]
        if url.startswith("@site:"):                         # a page of the site, from the site root
            return "../" * (self.depth + 1) + url[6:]
        if urlsplit(url).scheme or url.startswith("#"):
            return url
        path, _, frag = url.partition("#")
        suffix = "#" + frag if frag else ""
        if path == "README.md":
            return (self.up or "./") + suffix
        if path in SITE_PAGES:
            return f"{self.up}{SITE_PAGES[path]}{suffix}"
        topic = topic_of_md(self.data, path)
        if topic is not None and topic["status"] == "ready":
            return f"{self.up}{topic['id']}/{suffix}"
        if topic is not None:
            return (self.up or "./") + suffix or "./"
        return GITHUB + posixpath.normpath(posixpath.join(TUT, path)) + suffix

    def audio(self, url):
        return self.up + "audio/" + posixpath.basename(url)

    def image(self, url):
        return self.up + url if url.startswith("img/") else url


def inline(text, res):
    text = e(text)
    text = re.sub(r"!\[([^\]]*)\]\(([^)\s]+)\)", lambda m: f'<img src="{e(res.image(html.unescape(m[2])))}" alt="{m[1]}">', text)
    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", lambda m: f'<a href="{e(res.link(html.unescape(m[2])))}">{m[1]}</a>', text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    return re.sub(r"(?<![\w*])\*([^*]+)\*(?![\w*])", r"<em>\1</em>", text)


# ------------------------------------------------------------------------------------------------ blocks
def parse_blocks(lines):
    """Markdown lines -> blocks: ('h2', text) ('p', text) ('ul'|'ol', [items]) ('quote', [lines]) ('table', rows) ('fig', alt, url)."""
    blocks, cur = [], []

    def flush():
        if not cur:
            return
        first = cur[0]
        if first.startswith(">"):
            blocks.append(("quote", [re.sub(r"^>\s?", "", l) for l in cur]))
        elif first.startswith("|"):
            rows = [[c.strip() for c in l.strip().strip("|").split("|")] for l in cur if not re.fullmatch(r"\|[\s|:-]+\|", l.strip())]
            blocks.append(("table", rows))
        elif re.match(r"- ", first) or re.match(r"\d+\. ", first):
            kind, items = ("ul" if first.startswith("- ") else "ol"), []
            for l in cur:
                if re.match(r"(- |\d+\. )", l):
                    items.append(re.sub(r"^(- |\d+\. )", "", l))
                else:
                    items[-1] += " " + l.strip()
            blocks.append((kind, items))
        elif len(cur) == 1 and re.fullmatch(r"!\[[^\]]*\]\([^)\s]+\)", first):
            m = re.match(r"!\[([^\]]*)\]\(([^)\s]+)\)", first)
            blocks.append(("fig", m[1], m[2]))
        elif len(cur) == 1 and re.fullmatch(r"\[Listen: [^\]]+\]\([^)\s]+\.mp3\)", first):
            m = re.match(r"\[Listen: ([^\]]+)\]\(([^)\s]+)\)", first)
            blocks.append(("audio", m[1], m[2]))
        else:
            blocks.append(("p", " ".join(l.strip() for l in cur)))
        cur.clear()
    for line in lines:
        if line.startswith("<!--"):
            continue
        if line.startswith("## "):
            flush(); blocks.append(("h2", line[3:].strip()))
        elif not line.strip():
            flush()
        else:
            # a quote keeps its blank '>' lines inside the block
            if line.strip() == ">" and cur and cur[0].startswith(">"):
                cur.append(">")
            else:
                cur.append(line)
    flush()
    return blocks


ALERTS = {"NOTE": ("Note", "note"), "TIP": ("Tip", "tip"), "IMPORTANT": ("Important", "warn"), "WARNING": ("Careful", "warn"), "CAUTION": ("Careful", "warn")}


def render_blocks(blocks, res):
    """Blocks -> html; figures are returned apart (the step layout puts them beside the text)."""
    body, figs = [], []
    for b in blocks:
        kind = b[0]
        if kind == "p":
            body.append(f"<p>{inline(b[1], res)}</p>")
        elif kind in ("ul", "ol"):
            body.append(f"<{kind}>" + "".join(f"<li>{inline(i, res)}</li>" for i in b[1]) + f"</{kind}>")
        elif kind == "table":
            head = "".join(f"<th>{inline(c, res)}</th>" for c in b[1][0])
            rows = "".join("<tr>" + "".join(f"<td>{inline(c, res)}</td>" for c in r) + "</tr>" for r in b[1][1:])
            body.append(f'<div class="table-wrap"><table><thead><tr>{head}</tr></thead><tbody>{rows}</tbody></table></div>')
        elif kind == "audio":
            src = e(res.audio(b[2]))
            body.append(f'<figure class="listen"><audio controls preload="none" src="{src}" aria-label="{e(b[1])}">Your browser does not support audio playback.</audio>'
                        f'<figcaption><strong>{e(b[1])}</strong> · native DSP render, not a device recording · <a href="{src}" download>MP3</a></figcaption></figure>')
        elif kind == "fig":
            alt, url = b[1], b[2]
            src = e(res.image(url))
            if alt.startswith("Diagram"):
                caption = e(re.sub(r"^Diagram:\s*", "", alt))
                figs.append(("device", f'<figure class="dev"><img class="device" src="{src}" alt="{e(alt)}" loading="lazy"><figcaption>{caption}</figcaption></figure>'))
            else:
                figs.append(("screen", f'<figure><img class="screen" src="{src}" width="240" height="240" alt="{e(alt)}" loading="lazy">'
                                       f'<figcaption>{e(alt)} <span>(actual firmware display)</span></figcaption></figure>'))
        elif kind == "quote":
            lines = b[1]
            first = lines[0].strip()
            alert = re.fullmatch(r"\[!(\w+)\]", first)
            sixty_box = first.startswith("**In 60 seconds**")
            inner = parse_blocks([l if l != ">" else "" for l in lines[1:]] if (alert or sixty_box) else [l if l != ">" else "" for l in lines])
            inner_html, inner_figs = render_blocks(inner, res)
            if alert and alert[1] in ALERTS:
                label, cls = ALERTS[alert[1]]
                body.append(f'<aside class="callout {cls}"><strong>{label}</strong>{inner_html}</aside>')
            elif sixty_box:
                body.append(f'<aside class="sixty"><h2>In 60 seconds</h2>{inner_html}</aside>')
            else:
                body.append(f"<blockquote>{inner_html}</blockquote>")
            figs.extend(inner_figs)
    return "".join(body), figs


def parse_page(text, data, depth=1):
    """The Markdown of a topic -> (title, lead html, sixty html, [(number|None, heading, body html, figs)])."""
    res = Resolver(data, depth)
    title, lines = "", []
    for line in text.splitlines():
        if line.startswith("# "):
            title = line[2:].strip()
        elif not line.startswith("<!-- SPDX"):
            lines.append(line)
    blocks = parse_blocks(lines)
    lead, sixty, sections, cur = [], "", [], None
    for b in blocks:
        if b[0] == "h2":
            m = re.match(r"(\d+)\.\s+(.*)", b[1])
            cur = [m[1] if m else None, m[2] if m else b[1], []]
            sections.append(cur)
        elif cur is None:
            lead.append(b)
        else:
            cur[2].append(b)
    def is_sixty(b):
        return b[0] == "quote" and b[1][0].startswith("**In 60 seconds**")
    lead_html, _ = render_blocks([b for b in lead if not is_sixty(b)], res)
    for b in lead:
        if is_sixty(b):
            sixty = render_blocks([b], res)[0]
    out = []
    for num, heading, blks in sections:
        body, figs = render_blocks(blks, res)
        out.append((num, heading, body, figs))
    return title, lead_html, sixty, out


