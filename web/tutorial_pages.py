def used_images(data, root=ROOT):
    names = {t["thumb"] for t in data["topics"]} | {data["hero_device"]}
    for t in data["topics"]:
        if t["status"] == "ready":
            names |= set(re.findall(r"\]\(img/([^)\s]+)\)", (root / TUT / t["md"]).read_text(encoding="utf-8")))
    return sorted(names)


def used_audio(data, root=ROOT):
    names = set()
    for t in data["topics"]:
        if t["status"] == "ready":
            names |= {Path(u).name for u in re.findall(r"\[Listen: [^\]]+\]\(([^)\s]+\.mp3)\)", (root / TUT / t["md"]).read_text(encoding="utf-8"))}
    return sorted(names)


def add_tutorials(site, look, ship, version, root=ROOT):
    """The overview at tutorials/index.html, a page per ready topic and their images; safe to repeat. The STASIS lessons
    that used to be tutorials/index.html are written by stasis_pages (tutorials/stasis/)."""
    site = Path(site)
    data = load_topics(root)
    tutorials = site / "tutorials"
    (tutorials / "img").mkdir(parents=True, exist_ok=True)
    for name in used_images(data, root):
        shutil.copyfile(root / TUT / "img" / name, tutorials / "img" / name)
    audio = used_audio(data, root)
    if audio:
        (tutorials / "audio").mkdir(exist_ok=True)
    for name in audio:
        shutil.copyfile(root / "docs/audio/tutorials" / name, tutorials / "audio" / name)
    for t in data["topics"]:
        if t["status"] == "ready":
            (tutorials / t["id"]).mkdir(exist_ok=True)
            (tutorials / t["id"] / "index.html").write_text(topic_page(t, data, look, ship, version, root), encoding="utf-8")
    (tutorials / "index.html").write_text(overview_page(data, look, ship, version, root), encoding="utf-8")
    return data


