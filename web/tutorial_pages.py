def readme_link(href):
    """A registry link as it reads in docs/tutorials/README.md."""
    if href.startswith("@github:docs/tutorials/"):
        return href[len("@github:docs/tutorials/"):]
    if href.startswith("@github:"):
        return "../../" + href[8:]
    if href.startswith("@site:"):
        return SITE_URL.rsplit("tutorials/", 1)[0] + href[6:]
    return href if urlsplit(href).scheme else SITE_URL + href


