    body.append(f'<p><a class="btn" href="../">All tutorials</a> <a class="btn" href="../../emulator/">Try the emulator</a> <a class="btn" href="../../sounds/">Sound examples</a></p>')
    return shell(title, "".join(body), look, ship, version, "../../", description=f"Caravel tutorial: {title}. {topic['tagline']}")


